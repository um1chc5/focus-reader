export const T = (key) => I18N[st.lang][key];

export function fmtDate(ms) {
  try {
    return new Intl.DateTimeFormat(st.lang === 'vi' ? 'vi-VN' : 'en', { dateStyle: 'medium' }).format(new Date(ms));
  } catch {
    return new Date(ms).toLocaleDateString();
  }
}
